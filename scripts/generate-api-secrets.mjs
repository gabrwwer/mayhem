#!/usr/bin/env node
/**
 * Generate and install the API credentials the dashboard and bot need.
 *
 *   node scripts/generate-api-secrets.mjs [--force]
 *
 * Writes:
 *   apps/bot/.env            API_AUTH_TOKEN, INTERNAL_API_SECRET
 *   apps/dashboard/.env.local VITE_API_TOKEN  (mirrors API_AUTH_TOKEN)
 *
 * The generated values are NEVER printed. A credential echoed to a terminal
 * ends up in shell history, scrollback and any session transcript; there is no
 * reason for a human to read these, so they go straight to disk.
 *
 * Existing non-empty values are preserved unless --force is passed, so running
 * this twice cannot silently invalidate a working setup.
 *
 * Two independent secrets are generated. API_AUTH_TOKEN guards the dashboard →
 * API boundary (portfolio data, kill switch). INTERNAL_API_SECRET signs the
 * bot → API channel, whose payloads are rendered to the operator as evidence
 * for intervention decisions. Sharing one value across both would mean a
 * compromise of either grants both.
 */

import { randomBytes } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const BOT_ENV = path.join(REPO_ROOT, "apps", "bot", ".env");
const DASHBOARD_ENV = path.join(REPO_ROOT, "apps", "dashboard", ".env.local");

const force = process.argv.includes("--force");

/** 256 bits, base64url — no characters that need quoting in a .env file. */
function generateSecret() {
  return randomBytes(32).toString("base64url");
}

function readValue(contents, key) {
  const match = new RegExp(`^${key}=(.*)$`, "m").exec(contents);
  return match ? match[1].trim() : null;
}

/**
 * Replace a key's value in place, preserving comments, ordering and every
 * other line. Only rewrites keys that already exist — never appends, matching
 * the behaviour of apps/api/src/env-file.ts so this script cannot introduce
 * unreviewed config surface.
 */
function replaceValue(contents, key, value) {
  const pattern = new RegExp(`^${key}=.*$`, "m");
  if (!pattern.test(contents)) {
    throw new Error(
      `${key} not found in ${BOT_ENV}. Add the key (it may be empty) and re-run.`,
    );
  }
  return contents.replace(pattern, `${key}=${value}`);
}

/** Atomic write at 0600. A half-written .env means default risk limits on next boot. */
function writeFileAtomic(filePath, contents) {
  const tmp = `${filePath}.${process.pid}.tmp`;
  const handle = fs.openSync(tmp, "w", 0o600);
  try {
    fs.writeFileSync(handle, contents);
    fs.fsyncSync(handle);
  } finally {
    fs.closeSync(handle);
  }
  try {
    fs.renameSync(tmp, filePath);
  } catch (error) {
    try {
      fs.unlinkSync(tmp);
    } catch {
      // best effort — never leave a temp file masquerading as config
    }
    throw error;
  }
}

function main() {
  if (!fs.existsSync(BOT_ENV)) {
    console.error(`Bot .env not found at ${BOT_ENV}`);
    process.exit(1);
  }

  let contents = fs.readFileSync(BOT_ENV, "utf8");
  const changed = [];
  const skipped = [];

  const existingAuth = readValue(contents, "API_AUTH_TOKEN");
  const existingInternal = readValue(contents, "INTERNAL_API_SECRET");

  const apiToken = existingAuth && !force ? existingAuth : generateSecret();
  const internalSecret =
    existingInternal && !force ? existingInternal : generateSecret();

  if (existingAuth && !force) {
    skipped.push("API_AUTH_TOKEN");
  } else {
    contents = replaceValue(contents, "API_AUTH_TOKEN", apiToken);
    changed.push("API_AUTH_TOKEN");
  }

  if (existingInternal && !force) {
    skipped.push("INTERNAL_API_SECRET");
  } else {
    contents = replaceValue(contents, "INTERNAL_API_SECRET", internalSecret);
    changed.push("INTERNAL_API_SECRET");
  }

  if (changed.length > 0) {
    writeFileAtomic(BOT_ENV, contents);
  }

  // The dashboard token must equal the API token or every request returns 401.
  // Rewriting this file wholesale is safe: it holds only build-time frontend
  // config, never bot behaviour.
  const dashboardEnv = [
    "# Generated by scripts/generate-api-secrets.mjs — do not commit.",
    "# Must match API_AUTH_TOKEN in apps/bot/.env.",
    "# Vite inlines this at build time: restart the dev server after changes.",
    `VITE_API_TOKEN=${apiToken}`,
    "",
  ].join("\n");

  writeFileAtomic(DASHBOARD_ENV, dashboardEnv);

  console.log("API credentials installed.\n");
  if (changed.length > 0) {
    console.log(`  generated : ${changed.join(", ")}`);
  }
  if (skipped.length > 0) {
    console.log(`  kept      : ${skipped.join(", ")}  (use --force to regenerate)`);
  }
  console.log(`  bot env   : ${BOT_ENV}`);
  console.log(`  dash env  : ${DASHBOARD_ENV}`);
  console.log("\nValues are not printed by design. Restart the API, bot and");
  console.log("dashboard dev server for these to take effect.");
}

main();
